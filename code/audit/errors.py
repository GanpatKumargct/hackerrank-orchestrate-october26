"""Canonical reason codes (plan A.8.4) and loader errors."""
from enum import Enum


class SchemaError(Exception):
    """Raised by the loader when input validation fails; carries every error found."""

    def __init__(self, errors):
        self.errors = list(errors)
        super().__init__(f"{len(self.errors)} input validation error(s):\n" + "\n".join(self.errors))


